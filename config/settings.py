def _get_allowed_hosts(environ):
    hosts = [
        host.strip()
        for host in environ.get(
            "DJANGO_ALLOWED_HOSTS",
            "localhost,127.0.0.1",
        ).split(",")
        if host.strip()
    ]
    for name in ("VERCEL_URL", "VERCEL_PROJECT_PRODUCTION_URL"):
        host = environ.get(name, "").strip()
        if host and host not in hosts:
            hosts.append(host)
    return hosts


